import React from 'react';

export const StatusBadge = ({ type = 'optional', label = null }) => {
  if (type === 'compulsory') {
    return (
      <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-[11px] font-bold bg-emerald-50 text-emerald-800 border border-emerald-300 shadow-2xs">
        <span
          className="w-2 h-2 rounded-full bg-emerald-500 inline-block shrink-0 shadow-2xs ring-1 ring-emerald-600/30"
          aria-hidden="true"
        />
        <span>{label || 'Compulsory'}</span>
      </span>
    );
  }

  if (type === 'automatic') {
    return (
      <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-[11px] font-semibold bg-slate-100 text-slate-700 border border-slate-300 font-mono shadow-2xs">
        <span className="text-[11px]" aria-hidden="true">⚙️</span>
        <span>{label || 'Automatic'}</span>
      </span>
    );
  }

  return (
    <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-[11px] font-medium bg-rose-50 text-rose-800 border border-rose-300 shadow-2xs">
      <span
        className="w-2 h-2 rounded-full bg-rose-500 inline-block shrink-0 shadow-2xs ring-1 ring-rose-600/30"
        aria-hidden="true"
      />
      <span>{label || 'Optional'}</span>
    </span>
  );
};

